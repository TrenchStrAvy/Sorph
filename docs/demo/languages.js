// Pick the Whisper model that can actually decode `language`: settings.py's
// model_for_language. The .en models are English-only; any other language
// uses the multilingual sibling of the same size (small.en → small).
export function modelForLanguage(model, language) {
  return language !== 'en' && model.endsWith('.en') ? model.slice(0, -3) : model;
}

// Menu label: native name, with the English name when it differs.
export function label([, native, english]) {
  return native === english ? native : `${native} (${english})`;
}
